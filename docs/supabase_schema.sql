create policy "profiles_select_all"
on public.profiles for select
using (true);

create policy "profiles_insert_own"
on public.profiles for insert
with check (auth.uid() = id);

create policy "profiles_update_own"
on public.profiles for update
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "health_profiles_own_all"
on public.user_health_profiles for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "physiotherapists_select_all"
on public.physiotherapists for select
using (true);

create policy "physiotherapists_insert_own"
on public.physiotherapists for insert
with check (auth.uid() = id);

create policy "physiotherapists_update_own"
on public.physiotherapists for update
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "support_requests_select_participants"
on public.support_requests for select
using (auth.uid() = user_id or auth.uid() = physiotherapist_id);

create policy "support_requests_insert_user"
on public.support_requests for insert
with check (auth.uid() = user_id);

create policy "support_requests_update_physio"
on public.support_requests for update
using (auth.uid() = physiotherapist_id)
with check (auth.uid() = physiotherapist_id);

create policy "messages_select_participants"
on public.messages for select
using (
  exists (
    select 1
    from public.support_requests sr
    where sr.id = messages.thread_id
      and (sr.user_id = auth.uid() or sr.physiotherapist_id = auth.uid())
  )
);

create policy "messages_insert_participants"
on public.messages for insert
with check (
  exists (
    select 1
    from public.support_requests sr
    where sr.id = messages.thread_id
      and (sr.user_id = auth.uid() or sr.physiotherapist_id = auth.uid())
  )
);

